/* =========================================================================
   LAHORE LEGACY — DOWNLOAD + OPTIMISE PHOTOS (run once, on your computer)

   Downloads every Wikimedia Commons photo listed in js/config/assets.js,
   converts each to WebP in two sizes, saves them in assets/photos/ and
   writes js/config/local-photos.js. After that the site loads photos from
   your own server: no redirects, small WebP files, much faster.

     cd lahore-legacy
     npm install sharp
     node tools/fetch-photos.mjs

   Needs Node 18 or newer. Re-run after you add or change photos.
   Keep the "Photo credits" footer link: the Commons licences require it.
   ========================================================================= */

import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.join(ROOT, "assets/photos");
const SIZES = { src: 1600, small: 480 };
const QUALITY = 72;
const UA = "LahoreLegacyPhotoFetcher/1.0 (personal heritage website)";

// load LL.ASSETS from assets.js
const ctx = { window: {} };
ctx.LL = ctx.window.LL = {};
vm.createContext(ctx);
vm.runInContext(await fs.readFile(path.join(ROOT, "js/config/assets.js"), "utf8"), ctx);
const A = ctx.LL.ASSETS;
const places = { ...A.locations, ...A.extras };

async function originalUrl(file) {
  const api = "https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url&iiurlwidth=1920&titles=" + encodeURIComponent("File:" + file);
  const j = await (await fetch(api, { headers: { "User-Agent": UA } })).json();
  const pg = Object.values(j.query.pages)[0];
  if (!pg.imageinfo) throw new Error("not found on Commons");
  return pg.imageinfo[0].thumburl || pg.imageinfo[0].url;
}

const manifest = {};
let ok = 0, fail = 0;
await fs.mkdir(OUT, { recursive: true });
for (const [id, place] of Object.entries(places)) {
  manifest[id] = [];
  const files = place.gallery || [];
  for (let i = 0; i < files.length; i++) {
    const g = files[i];
    try {
      const url = await originalUrl(g.file);
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (!res.ok) throw new Error("HTTP " + res.status);
      const buf = Buffer.from(await res.arrayBuffer());
      const base = `${id}-${i + 1}`;
      const big = await sharp(buf).rotate().resize({ width: SIZES.src, withoutEnlargement: true }).webp({ quality: QUALITY }).toBuffer({ resolveWithObject: true });
      const small = await sharp(buf).rotate().resize({ width: SIZES.small, withoutEnlargement: true }).webp({ quality: QUALITY - 4 }).toBuffer();
      await fs.writeFile(path.join(OUT, base + ".webp"), big.data);
      await fs.writeFile(path.join(OUT, base + "-sm.webp"), small);
      manifest[id].push({ src: `assets/photos/${base}.webp`, small: `assets/photos/${base}-sm.webp`, w: big.info.width, h: big.info.height, file: g.file, caption: g.caption, ur: g.ur });
      ok++;
      console.log("✓", base, `${Math.round(big.data.length / 1024)} KB`);
      await new Promise((r) => setTimeout(r, 300)); // be polite to Wikimedia
    } catch (e) {
      fail++;
      console.warn("✗", id, g.file, "-", e.message);
    }
  }
  if (!manifest[id].length) delete manifest[id];
}

const js = `/* Generated by tools/fetch-photos.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand. */\nwindow.LL = window.LL || {};\nLL.LOCAL_PHOTOS = ${JSON.stringify(manifest, null, 1)};\n`;
await fs.writeFile(path.join(ROOT, "js/config/local-photos.js"), js);
console.log(`\nDone: ${ok} photos saved, ${fail} failed. Wrote js/config/local-photos.js`);
